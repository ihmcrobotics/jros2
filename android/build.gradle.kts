// Auto-detect and set Android SDK location
val localPropertiesFile = file("local.properties")
if (!localPropertiesFile.exists()) {
   val androidSdkPath = findAndroidSdk()
   if (androidSdkPath != null) {
      println("Auto-detected Android SDK at: $androidSdkPath")
      FileOutputStream(localPropertiesFile).use { output ->
         val props = Properties()
         props.setProperty("sdk.dir", androidSdkPath)
         props.store(output, "Auto-generated by Gradle build script")
      }
   } else {
      logger.warn("Could not auto-detect Android SDK location. Please set ANDROID_HOME or ANDROID_SDK_ROOT environment variable, or create local.properties with sdk.dir")
   }
}

fun findAndroidSdk(): String? {
   // Try environment variables first
   listOf("ANDROID_HOME", "ANDROID_SDK_ROOT").forEach { envVar ->
      val sdkPath = System.getenv(envVar)
      if (sdkPath != null && File(sdkPath).exists()) {
         return sdkPath
      }
   }

   // Try common installation locations
   val homeDir = System.getProperty("user.home")
   val commonPaths = listOf(
      "$homeDir/Android/Sdk",
      "$homeDir/Library/Android/sdk", // macOS
      "/usr/local/android-sdk",
      "/opt/android-sdk"
   )

   for (path in commonPaths) {
      if (File(path).exists()) {
         return path
      }
   }

   return null
}

