package us.ihmc.jros2.generator;

import org.gradle.api.Project;
import org.gradle.testfixtures.ProjectBuilder;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import us.ihmc.jros2.parser.field.InterfaceFieldParsingException;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/**
 * {@link jros2GenTask}, the Gradle task users run to generate message classes, executed in a Gradle {@link ProjectBuilder}
 * project: its inputs must reach the generator (package paths, dependency paths for type hashes, hand-written type
 * mappings, output directory cleaning), and an invalid .msg file must fail the task with the parser's message.
 */
public class jros2GenTaskTest
{
   /**
    * The Gradle user home of the test projects. ProjectBuilder extracts Gradle's native libraries into it and loads them once
    * per JVM, so it is kept out of the temporary directories JUnit deletes after each test: a loaded library cannot be
    * deleted on Windows, and later projects of the same JVM keep using the libraries of the first one.
    */
   private static final Path GRADLE_USER_HOME = Path.of("build", "tmp", "jros2GenTaskTest", "gradle-user-home").toAbsolutePath();

   private static jros2GenTask newTask(Path directory) throws IOException
   {
      Path projectDirectory = Files.createDirectories(directory.resolve("project"));
      Project project = ProjectBuilder.builder()
                                      .withProjectDir(projectDirectory.toFile())
                                      .withGradleUserHomeDir(Files.createDirectories(GRADLE_USER_HOME).toFile())
                                      .build();
      project.getPlugins().apply(jros2GeneratorPlugin.class);
      return project.getTasks().register("generateMessages", jros2GenTask.class).get();
   }

   @Test
   public void testTaskGeneratesWithDependencyPathsTypeMappingsAndCleaning(@TempDir Path directory) throws Exception
   {
      writePackages(directory);
      Path output = directory.resolve("out");
      Path stale = Files.createDirectories(output.resolve("old_pkg")).resolve("Stale.java");
      Files.writeString(stale, "// generated by an earlier run\n");

      jros2GenTask task = newTask(directory);
      // Defaults of a new task
      assertNotNull(task.getDependencyPaths());
      assertTrue(task.getDependencyPaths().isEmpty());
      assertNotNull(task.getTypeToClass());
      assertTrue(task.getTypeToClass().isEmpty());
      assertFalse(task.isCleanOutputDir());
      assertEquals("IHMC", task.getFormat());

      task.setPackagePaths(List.of(directory.resolve("user_pkg").toString()));
      task.setDependencyPaths(List.of(directory.resolve("deps").toString()));
      task.setTypeToClass(Map.of("user_pkg/Mapped", "com.example.CustomMapped"));
      task.setOutputDir(output.toString());
      task.setCleanOutputDir(true);

      assertEquals(List.of(directory.resolve("user_pkg").toString()), task.getPackagePaths());
      assertEquals(List.of(directory.resolve("deps").toString()), task.getDependencyPaths());
      assertEquals(Map.of("user_pkg/Mapped", "com.example.CustomMapped"), task.getTypeToClass());
      assertEquals(output.toString(), task.getOutputDir());
      assertTrue(task.isCleanOutputDir());

      task.run();

      assertFalse(Files.exists(stale), "cleanOutputDir must delete the old output");
      assertFalse(Files.exists(output.resolve("user_pkg/Mapped.java")), "types mapped to hand-written classes are not generated");
      assertFalse(Files.exists(output.resolve("dep_pkg")), "dependency packages are not generated");

      String user = Files.readString(output.resolve("user_pkg/User.java"));
      assertTrue(user.contains("com.example.CustomMapped mapped_"), user);
      // The hash needs the definition of dep_pkg/Dep, which only the dependency path provides
      assertTrue(user.contains("typeHash = \"RIHS01_"), user);
      new jros2InterfaceGenerator().addPackagePath(directory.resolve("user_pkg"))
                                   .addDependencyPath(directory.resolve("deps"))
                                   .setTypeToClass(Map.of("user_pkg/Mapped", "com.example.CustomMapped"))
                                   .setOutputDir(directory.resolve("reference"))
                                   .generate();
      assertEquals(Files.readString(directory.resolve("reference/user_pkg/User.java")), user,
                   "the task must generate exactly what the generator generates for the same inputs");
   }

   @Test
   public void testTaskWithoutDependencyPathsStillGenerates(@TempDir Path directory) throws Exception
   {
      writePackages(directory);
      Path output = directory.resolve("out");
      Path kept = Files.createDirectories(output.resolve("hand_written")).resolve("Keep.java");
      Files.writeString(kept, "// not generated\n");

      jros2GenTask task = newTask(directory);
      task.setPackagePaths(List.of(directory.resolve("user_pkg").toString()));
      task.setDependencyPaths(null);
      task.setOutputDir(output.toString());
      task.run();

      assertTrue(Files.exists(kept), "without cleanOutputDir other files in the output directory are kept");
      assertTrue(Files.exists(output.resolve("user_pkg/Mapped.java")));
      // dep_pkg/Dep cannot be resolved: generation succeeds without a hash
      assertTrue(Files.readString(output.resolve("user_pkg/User.java")).contains("typeHash = null;"));
   }

   @Test
   public void testInvalidMessageFailsTheTaskWithTheParserMessage(@TempDir Path directory) throws Exception
   {
      GeneratorGoldenTest.writePackage(directory.resolve("bad_pkg"), Map.of("Bad.msg", "int32 x\nint32 x\n"));

      jros2GenTask task = newTask(directory);
      task.setPackagePaths(List.of(directory.resolve("bad_pkg").toString()));
      task.setOutputDir(directory.resolve("out").toString());

      RuntimeException exception = assertThrows(RuntimeException.class, task::run);
      assertInstanceOf(InterfaceFieldParsingException.class, exception.getCause());
      assertEquals(exception.getCause().getMessage(), exception.getMessage());
      assertFalse(Files.exists(directory.resolve("out/bad_pkg/Bad.java")));
   }

   private static void writePackages(Path directory) throws IOException
   {
      GeneratorGoldenTest.writePackage(directory.resolve("deps").resolve("dep_pkg"), Map.of("Dep.msg", "string label\n"));
      GeneratorGoldenTest.writePackage(directory.resolve("user_pkg"), Map.of("Mapped.msg", "int32 x\n", "User.msg", "Mapped mapped\ndep_pkg/Dep dep\n"));
   }

   @Test
   public void testFormatOption(@TempDir Path directory) throws Exception
   {
      jros2GenTask task = newTask(directory);
      task.setFormat("google");
      assertEquals("GOOGLE", task.getFormat());
      task.setFormat("IHMC");
      assertEquals("IHMC", task.getFormat());
      assertThrows(IllegalArgumentException.class, () -> task.setFormat("tabs"));
      assertFalse(task.getGoogleJavaFormatVersion().isEmpty());
   }
}
