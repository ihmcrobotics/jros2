package us.ihmc.jros2.generator;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.Set;
import java.util.stream.Stream;

final class GeneratedMessageFileCleanup
{
   static final String GENERATED_FILE_MARKER = "This class was automatically generated by jros2";

   private GeneratedMessageFileCleanup()
   {
   }

   static void cleanOutputDirectory(Path outputDir) throws IOException
   {
      if (!Files.exists(outputDir))
         return;

      try (Stream<Path> walk = Files.walk(outputDir))
      {
         walk.sorted(Comparator.reverseOrder())
             .filter(path -> !path.equals(outputDir))
             .forEach(path ->
             {
                try
                {
                   Files.deleteIfExists(path);
                }
                catch (IOException e)
                {
                   throw new RuntimeException("Failed to delete " + path, e);
                }
             });
      }
   }

   static int removeOrphanedGeneratedFiles(Path outputDir, Set<Path> generatedPaths) throws IOException
   {
      if (!Files.exists(outputDir))
         return 0;

      int removedCount = 0;

      try (Stream<Path> walk = Files.walk(outputDir))
      {
         for (Path path : walk.filter(candidate -> Files.isRegularFile(candidate) && candidate.toString().endsWith(".java")).toList())
         {
            Path normalizedPath = path.toAbsolutePath().normalize();
            if (generatedPaths.contains(normalizedPath))
               continue;

            if (!isJros2GeneratedFile(path))
               continue;

            Files.deleteIfExists(path);
            System.out.printf("Removed orphaned generated file | %s%n", path.toAbsolutePath());
            removedCount++;
         }
      }

      return removedCount;
   }

   static boolean isJros2GeneratedFile(Path path) throws IOException
   {
      if (!Files.isRegularFile(path))
         return false;

      byte[] headerBytes = Files.readAllBytes(path);
      if (headerBytes.length > 4096)
      {
         byte[] truncatedHeader = new byte[4096];
         System.arraycopy(headerBytes, 0, truncatedHeader, 0, truncatedHeader.length);
         headerBytes = truncatedHeader;
      }

      return new String(headerBytes, StandardCharsets.UTF_8).contains(GENERATED_FILE_MARKER);
   }
}
